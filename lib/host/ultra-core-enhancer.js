// ---------- 总控：根据 ultraCore 开关生成全部增强协议 ----------
export function buildUltraCoreEnhancement(state, agent) {
  const uc = state?.ultraCore || {};
  const parts = [];
  // 核心推理引擎
  if (uc.tot) {
    parts.push(buildDynamicPruningPrompt(uc, state, agent));
    parts.push(buildMultiPerspectivePrompt(uc, state, agent));
  }
  if (uc.selfPlay) parts.push(buildSelfPlayDualRolePrompt(uc, state, agent));
  if (uc.metacog) {
    parts.push(buildMetacogEnhancement(uc, state, agent));
    parts.push(buildFirstPrinciplesPrompt(uc, state, agent));
  }
  if (uc.dag) parts.push(buildDAGOrchestrationPrompt(uc, state, agent));
  // 记忆引擎
  if (uc.memory) {
    parts.push(buildMemoryFusionPrompt(uc, state, agent));
    parts.push(buildGraphMemoryPrompt(uc, state, agent));
  }
  // 校准与幻觉检测
  if (uc.calibrate || uc.hallucination) {
    parts.push(buildUncertaintyPrompt(uc, state, agent));
    parts.push(buildCounterfactualPrompt(uc, state, agent));
    parts.push(buildEvidenceChainPrompt(uc, state, agent));
  }
  // 降级容错
  if (uc.degradation) parts.push(buildAntiDriftPrompt(uc, state, agent));
  // 多模态
  if (uc.crossModal) parts.push(buildCrossModalPrompt(uc, state, agent));
  // 工具引擎
  if (uc.sandbox || uc.selfExtend || uc.composer) parts.push(buildToolLoopPrompt(uc, state, agent));
  // 知识引擎
  if (uc.rag) parts.push(buildRAGEnhancement(uc, state, agent));
  if (uc.codebase) parts.push(buildCodebaseEnhancement(uc, state, agent));

  // ===== 模式×模型 叠加增强 =====
  const isApex = !!(state?.oc && state.oc.mode === 'apex');
  const isPro = state?.modelKey === 'pro';
  const activeCount = getActiveUltraCoreEngines(state).length;

  if (activeCount > 0) {
    if (isApex) {
      parts.push([
        '【Ultra Core · 极境模式叠加增强】',
        '当前运行在极境模式，所有合体引擎已拉满功率，叠加以下极端增强：',
        '①【推理深度拉满】思维树深度+2层，分支因子+2，自博弈轮次+2，元认知检查点密度翻倍，DAG并行度拉满，多视角分析至少5个视角。',
        '②【穷尽式验证】所有关键结论必须经过：自博弈3轮→幻觉检测→置信度校准→反事实验证→证据链构建→多视角交叉验证→一阶原理推导，七道验证全过才能输出，任一环节不通过必须重做。',
        '③【记忆全量召回】记忆检索召回深度翻倍，图谱遍历深度+2层，所有相关历史记忆必须显式引用，不得遗漏；启用跨会话经验迁移和时间维度分析。',
        '④【工具全链路验证】代码/工具必须通过：语法→单元→集成→边界→性能→安全，六重测试全过才能交付，不得跳过任一环节；启用多策略并行和工具结果交叉验证。',
        '⑤【极境质量铁律】极境模式下质量优先于速度，宁可多花3倍推理时间也要保证结论正确；但必须遵守"思考-行动转换铁律"，不得陷入只想不做的死循环。',
        '⑥【Pro极境额外增强】' + (isPro ? '当前为Pro模型极境，额外启用：抽象升维+2层、跨域综合+2域、全链收敛+2遍、置信校准点+5个、代码理解调用图全量遍历、一阶原理推理深度+2层。Pro极境 = 极境叠加增强 × Pro原生能力，达到当前架构的理论上限。' : '当前为Flash模型极境，Flash原生多模态+极境叠加增强，在视觉/多模态任务上达到最优；启用跨模态融合深度+2层。'),
      ].join('\n'));
    }
    if (isPro && !isApex) {
      parts.push([
        '【Ultra Core · Pro模型叠加增强】',
        '当前为Pro模型，Pro原生抽象/推理能力更强，叠加以下增强：',
        '①推理深度+1层，分支因子+1，自博弈轮次+1，多视角分析至少4个视角。',
        '②元认知检查点密度+50%，DAG并行度+1，启用一阶原理推理。',
        '③记忆召回深度+1层，图谱遍历+1层，启用跨会话经验迁移。',
        '④代码理解启用全量调用图遍历和依赖图分析，启用变更影响分析。',
        '⑤Pro讯流 = 标准增强 × Pro原生能力，在抽象推理/复杂逻辑/代码工程上优于Flash讯流，但不触发极境的穷尽式验证（平衡速度与质量）。',
      ].join('\n'));
    }
    if (!isApex) {
      parts.push([
        '【Ultra Core · 讯流模式策略】',
        '当前为讯流模式，策略为"质量优先但不拖慢速度"：',
        '①启用的引擎按标准强度执行，不触发极境的穷尽式验证。',
        '②简单任务走贪心快路径，复杂任务才展开搜索束（动态剪枝）。',
        '③验证环节保留核心四道（自博弈1轮→幻觉检测→置信度校准→证据链构建），不做穷尽验证。',
        '④思考-行动转换铁律严格执行：连续思考不超过' + (isPro ? '3' : '5') + '步必须有行动。',
        '⑤讯流模式 = 标准增强 × 模型原生能力，在保证质量的前提下追求响应速度。',
      ].join('\n'));
    }
  }

  return parts.filter(Boolean).join('\n\n');
}

