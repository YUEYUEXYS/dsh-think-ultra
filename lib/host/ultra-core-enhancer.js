// ---------- 1. 混合记忆融合增强 ----------
// 三层记忆架构：向量语义检索 + 知识图谱推理 + 键值快速缓存
export function buildMemoryFusionPrompt(ultraCore, state, agent) {
  if (!ultraCore || !ultraCore.memory) return '';
  const memTier = Math.max(1, Math.min(5, Math.round(Number(state.sliders?.memory) || 3)));
  const recallDepth = memTier * 3;
  const consolidateEvery = Math.max(2, 6 - memTier);
  return [
    '【Ultra Core · 混合记忆融合】',
    '你运行在三层混合记忆系统之上：①向量语义检索（按语义相似度召回相关历史）②知识图谱（实体-关系-属性结构化记忆，支持遍历推理）③键值缓存（高频事实快速命中）。',
    `硬性规则：①每次推理开始前，必须主动检索与当前任务相关的历史记忆（召回深度 ${recallDepth} 条），不得凭印象回答；②推理过程中产生的重要结论、决策、用户偏好、项目上下文，必须立即沉淀到记忆系统（标注重要性等级 0.0-1.0）；③每 ${consolidateEvery} 轮推理后，必须做一次记忆整合：合并相似记忆、消解矛盾、提取核心知识图谱节点；④引用记忆时必须标注来源（"据记忆：..."），不得把记忆内容伪装成即时推理；⑤记忆检索无结果时，明确声明"无相关历史记忆"，不得编造记忆内容；⑥记忆冲突时必须显式标注"记忆冲突：历史说X，当前证据说Y"，以最新证据为准但保留历史记录。`,
    memTier >= 3 ? '中级模式：启用记忆重要性自动评估——每条新记忆自动评估重要性（基于用户关注度、复用频率、任务关键性），重要性>0.7的记忆跨会话优先召回，<0.3的记忆按半衰期衰减。' : '',
    memTier >= 4 ? '高级模式：启用跨会话记忆迁移——主动识别当前任务与历史任务的相似性，将相关历史经验（成功方案、失败教训、关键决策）迁移到当前任务，并标注"经验迁移：来自历史任务XXX"。' : '',
    memTier >= 5 ? '极限模式：启用记忆图谱自动推理——通过实体关系遍历发现隐含关联（A→B→C 推导 A 与 C 的间接关系），在回答中显式标注"记忆图谱推理：..."；启用记忆时间维度分析，识别用户偏好的演变趋势。' : '',
  ].filter(Boolean).join('\n');
}

// ---------- 2. 自博弈多角色推理增强 ----------
