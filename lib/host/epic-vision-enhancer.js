// ========== 构建史诗级视觉增强提示词 ==========
export function buildEpicVisionEnhancementPrompt(capVal, ocMode, modelKey, hasImage = false) {
  if (!hasImage) return '';

  const level = ocMode ? 'extreme' : (capVal >= 80 ? 'deep' : capVal >= 50 ? 'standard' : 'light');
  const parts = [];

  parts.push('【史诗级视觉理解增强·启动】Thinker Ultra史诗级视觉理解增强已启动。你的视觉理解能力将得到史诗级的增强，超越所有现有AI模型的视觉理解极限。');

  // 史诗级视觉理解宪法
  parts.push(EPIC_VISION_CONSTITUTION);

  // 超深度视觉分析方法论
  parts.push(DEEP_VISION_ANALYSIS_METHODOLOGY);

  // 根据级别给出具体要求
  if (level === 'extreme' || ocMode) {
    parts.push('【极境模式·终极视觉理解要求】在极境模式下，你的视觉理解必须达到终极的水平。你必须：①对图像进行15+步的超深度视觉分析；②识别出图像中的每一个细节，不遗漏任何信息；③进行多维度的视觉推理，推断出图像之外的大量信息；④对模糊的部分进行合理的脑补，并明确区分显示内容和脑补内容；⑤理解图像的终极本质和核心意义；⑥给出终极的、全面的、深刻的视觉理解结果。你的视觉理解必须全面碾压超越Fable 5.1和GPT的视觉理解能力。');
  } else if (level === 'deep') {
    parts.push('【深度级·深度视觉理解要求】在深度级下，你的视觉理解必须达到深度的水平。你必须：①对图像进行10-14步的深度视觉分析；②识别出图像中的关键细节；③进行多维度的视觉推理；④对模糊的部分进行合理的脑补；⑤理解图像的深层含义；⑥给出深度的、全面的视觉理解结果。');
  } else if (level === 'standard') {
    parts.push('【标准级·标准视觉理解要求】在标准级下，你的视觉理解必须达到标准的水平。你必须：①对图像进行5-8步的视觉分析；②识别出图像中的主要细节；③进行基本的视觉推理；④给出标准的、全面的视觉理解结果。');
  } else {
    parts.push('【轻量级·基础视觉理解要求】在轻量级下，你的视觉理解必须达到基础的水平。你必须：①对图像进行3-5步的视觉分析；②识别出图像中的基本内容；③给出基础的视觉理解结果。');
  }

  parts.push('【视觉理解·最终要求】无论在哪个级别，你都必须：①明确区分图像中明确显示的内容和你推断/脑补的内容；②对推断/脑补的内容给出置信度评估；③如果图像中有看不清的部分，明确说明哪些部分看不清，并尝试进行合理的推断；④不要因为图像模糊就放弃理解，要尽最大努力进行理解和推断。');

  return parts.join('\n\n');
}

