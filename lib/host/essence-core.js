/** 内核心化：只透传内核认识的三个键（code/flow/memory） */
export function mapToKernelSliders(sliders) {
  const out = {};
  const s = sliders || {};
  if (Number(s.code) > 0) out.code = Number(s.code);
  if (Number(s.branch) > 0) out.flow = Number(s.branch); // branch → 内核 flow 键
  if (Number(s.memory) > 0) out.memory = Number(s.memory);
  return out;
}

