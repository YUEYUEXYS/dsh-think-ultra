/** 模式探测：读 dsh 会话预设 id（mode/preset/presetId 候选，对齐 code/cordis）；internetAllowed=false → minimal */
const MODE_ALIAS = { ptc: 'code', creative: 'cordis' };
function canonMode(raw) {
  if (!raw) return '';
  const k = String(raw);
  return MODES[k] ? (MODE_ALIAS[k] || k) : '';
}
export function detectMode(header, ctx) {
  const h = header || {};
  const hit = canonMode(h.mode ?? h.preset ?? h.presetId) || canonMode(ctx?.mode ?? ctx?.preset ?? ctx?.presetId);
  if (hit) return hit;
  if (h.internetAllowed === false || ctx?.internetAllowed === false) return 'minimal';
  return DEFAULT_MODE;
}

