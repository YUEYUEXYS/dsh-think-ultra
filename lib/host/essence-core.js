// 本质键之外、后端真实消费的运行时档位键：verify 驱动审判工具箱，agent/longcode/consist/heal/reclaim
// 是稳定性折叠五杆（reclaim=资源回收/峰值压制，真接 resource-controller）。归一化时必须与本质键同等待遇
// 原样保留——此前白名单漏了它们，每次 activate/settingsSync 重建 sliders 时被清零，导致前端能拖、后端 eff() 恒为 0 的空转。
const RUNTIME_SLIDER_KEYS = ['verify', 'falsify', 'exec', 'agent', 'longcode', 'consist', 'heal', 'reclaim', 'watchdog', 'persist', 'checkpoint', 'converge', 'vmem', 'vpersist'];

/** 旧键值合并为新键值（同类取最大档，保证安全/深度不缩水）；本质键直通不被丢弃 */
export function mergeLegacySliders(legacy) {
  const out = {};
  for (const key of ESSENCE_KEYS) out[key] = 0;
  for (const key of RUNTIME_SLIDER_KEYS) out[key] = 0;
  for (const [oldKey, oldTier] of Object.entries(legacy || {})) {
    const newKey = (ESSENCE_KEYS.includes(oldKey) || RUNTIME_SLIDER_KEYS.includes(oldKey))
      ? oldKey
      : LEGACY_MAP[oldKey];
    if (!newKey) continue;
    const t = Math.max(0, Math.min(6, Math.round(Number(oldTier) || 0)));
    out[newKey] = Math.max(out[newKey] ?? 0, t);
  }
  return out;
}

