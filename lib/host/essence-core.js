/** 最终有效档位：能力上限 × 开放封顶 × 模式缩放。
 *  拉满语义：UI 档位达到开放封顶时再吃一档（超高满=极限实力，极限满=绝顶实力）。
 *  绝顶档(6)只在 unlock/cap 都允许时出现，绝不再被 min(5,...) 反向压回。 */
export function resolveEffective(modelKey, mode, sliderKey, uiTier) {
  const model = MODEL_CAPS[modelKey] || MODEL_CAPS[DEFAULT_MODEL];
  const modeCfg = MODES[mode] || MODES.standard;
  const cap = model.caps[sliderKey] ?? 0;
  if (cap <= 0) return 0;                                  // 该模型此滑杆不可用（如 vision 非视觉模型）
  const _uTbl = MODEL_UNLOCK[modelKey] || MODEL_UNLOCK[DEFAULT_MODEL];
  const unlock = (_uTbl && typeof _uTbl[sliderKey] === 'number') ? _uTbl[sliderKey] : cap;
  let base = Math.max(0, Math.min(6, Math.round(Number(uiTier) || 0)));
  if (unlock > 0 && base >= unlock) base = Math.min(cap, unlock); // 全部封顶，绝顶不再暗升
  const scaled = Math.floor(base * modeCfg.scale);
  return Math.max(0, Math.min(cap, scaled));
}

