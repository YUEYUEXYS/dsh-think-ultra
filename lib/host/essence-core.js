export const DEFAULT_MODEL = 'deepseek-v4-pro';

/** 宿主模型名 -> 模型 key（两模型通道：Flash / Pro）。
 *  V4.1 Flash（deepseek-v4.1-flash）为原生多模态，已正式接管原 Vision 识图能力，
 *  独立 Vision 模型（deepseek-v4-flash-vision-exp）已下架。故 flash / 旧 vision / vl /
 *  multimodal / image 标识统一归 Flash 通道，由 Flash 通道承载全部视觉锻造能力。 */
export function detectModel(modelString) {
  const m = String(modelString || '').toLowerCase();
  if (m.includes('pro')) return 'deepseek-v4-pro';
  // 独立视觉档（旧 vision-exp / 视觉实验模型）优先识别，键名必须命中 MODEL_CAPS
  if (m.includes('vision-exp') || m.includes('vision_exp') || m.includes('visionexp')) return 'deepseek-v4-flash-vision-exp';
  if (m.includes('flash') || m.includes('vl') || m.includes('multimodal') || m.includes('image')) return 'deepseek-v4-flash';
  // 裸 vision 标识默认归 Flash 文本通道（看图升档由 tool 层 effectiveTier 按 hasImage 处理）
  if (m.includes('vision')) return 'deepseek-v4-flash';
  return DEFAULT_MODEL; // 未知 → Pro 默认
}

