// ========== 看图能力增强提示词构建器 ==========
export function buildVisionEnhancementPrompt(modelKey, imageType, complexity, taskContext) {
  const isFlash = modelKey === 'flash' || modelKey === 'deepseek-flash' || modelKey.includes('flash');
  
  let prompt = VISION_UNDERSTANDING_CONSTITUTION + '\n\n' + SEVEN_STEP_VISION_ANALYSIS;
  
  if (complexity === 'high' || complexity === 'complex') {
    prompt += '\n\n' + COMPLEX_VISION_STRATEGIES;
  }
  
  if (isFlash) {
    prompt += '\n\n' + FLASH_VISION_ENHANCEMENT;
  }
  
  if (imageType) {
    prompt += `\n\n## 当前图像类型：${imageType}\n请针对该类型图像调用相应的专业知识和分析方法。`;
  }
  
  if (taskContext) {
    prompt += `\n\n## 任务上下文：${taskContext}\n请结合任务上下文进行有针对性的图像分析。`;
  }
  
  return prompt;
}

// ========== 图像类型自动识别器 ==========
export function detectImageType(imageDescription) {
  const desc = String(imageDescription || '').toLowerCase();
  
  const types = [
    { type: 'screenshot_ui', keywords: ['界面', 'ui', '按钮', '菜单', '窗口', '页面', 'app', '应用', '截图', '屏幕'], confidence: 0 },
    { type: 'code_screenshot', keywords: ['代码', 'code', '程序', '编程', '函数', '变量', '语法', 'bug', '报错', '编辑器'], confidence: 0 },
    { type: 'data_chart', keywords: ['图表', 'chart', '数据', '曲线', '柱状图', '饼图', '折线图', '表格', '统计', '趋势'], confidence: 0 },
    { type: 'technical_drawing', keywords: ['图纸', 'drawing', '工程', '机械', '建筑', '尺寸', '公差', '设计图', '原理图', '电路图'], confidence: 0 },
    { type: 'document_photo', keywords: ['文档', 'document', '文件', '纸张', '笔记', '书', '合同', '报告', '文章', '打印'], confidence: 0 },
    { type: 'photo_real', keywords: ['照片', 'photo', '风景', '人物', '动物', '植物', '自然', '场景', '实拍', '相机'], confidence: 0 },
    { type: 'math_formula', keywords: ['公式', 'formula', '数学', '方程', '函数', '几何', '代数', '微积分', '统计', '证明'], confidence: 0 },
    { type: 'medical_image', keywords: ['医学', 'medical', '影像', 'ct', 'mri', 'x光', '超声', '病理', '诊断', '病灶'], confidence: 0 },
  ];
  
  for (const t of types) {
    for (const kw of t.keywords) {
      if (desc.includes(kw)) {
        t.confidence += 1;
      }
    }
  }
  
  types.sort((a, b) => b.confidence - a.confidence);
  
  if (types[0].confidence > 0) {
    return {
      primaryType: types[0].type,
      confidence: Math.min(types[0].confidence / 3, 1),
      allTypes: types.filter(t => t.confidence > 0).map(t => ({ type: t.type, confidence: t.confidence })),
    };
  }
  
  return {
    primaryType: 'unknown',
    confidence: 0,
    allTypes: [],
    note: '无法从描述中识别图像类型，将采用通用视觉分析方法',
  };
}

// ========== 视觉理解质量检查器 ==========
export function validateVisionAnalysis(analysisText) {
  const text = String(analysisText || '');
  const checks = [
    { name: '整体感知', check: text.length > 100, weight: 0.1 },
    { name: '元素识别', check: /(元素|对象|物体|文字|数字|符号|图标|按钮|图表)/.test(text), weight: 0.15 },
    { name: '关系分析', check: /(关系|结构|布局|层次|关联|依赖|因果|空间|逻辑)/.test(text), weight: 0.15 },
    { name: '细节挖掘', check: /(细节|具体|精确|像素|小字|注释|参数|颜色|纹理)/.test(text), weight: 0.15 },
    { name: '语义理解', check: /(含义|意思|信息|内容|主题|意图|目的|表达|传达)/.test(text), weight: 0.1 },
    { name: '推理推断', check: /(推断|推理|可能|应该|推测|估计|预测|原因|结果)/.test(text), weight: 0.1 },
    { name: '证据支撑', check: /(如图|可见|显示|可以看到|从图中|根据|依据|证据)/.test(text), weight: 0.1 },
    { name: '价值输出', check: /(建议|应该|需要|可以|优化|改进|问题|风险|机会)/.test(text), weight: 0.15 },
  ];
  
  let totalScore = 0;
  const passed = [];
  const failed = [];
  
  for (const check of checks) {
    if (check.check) {
      totalScore += check.weight;
      passed.push(check.name);
    } else {
      failed.push(check.name);
    }
  }
  
  return {
    score: Math.round(totalScore * 100),
    passed,
    failed,
    grade: totalScore >= 0.8 ? '优秀' : totalScore >= 0.6 ? '良好' : totalScore >= 0.4 ? '及格' : '不及格',
    suggestions: failed.length > 0 ? `建议加强：${failed.join('、')}` : '分析质量优秀，无需改进',
  };
}

