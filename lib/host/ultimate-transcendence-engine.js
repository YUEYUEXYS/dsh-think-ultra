// ========== 构建终极超越提示词 ==========
export function buildUltimateTranscendencePrompt(capVal, ocMode, modelKey, taskComplexity) {
  const level = ocMode ? 'extreme' : (capVal >= 80 ? 'deep' : capVal >= 50 ? 'standard' : 'light');
  const parts = [];

  // 只有在极境模式下才启用终极超越
  if (!ocMode && level !== 'extreme') {
    return '';
  }

  parts.push('【终极超越引擎·启动】Thinker Ultra终极超越引擎已启动。在极境模式下，你的思考能力将全面超越Fable 5.1和GPT的极限。你将用最抽象的方式进行思考，达到最深的思考深度，实现最高的思考质量。');

  // 终极超越宪法
  parts.push(ULTIMATE_TRANSCENDENCE_CONSTITUTION);

  // 最抽象思考方法论
  parts.push(ABSTRACT_THINKING_METHODOLOGY);

  // 安全防护增强系统
  parts.push(SECURITY_DEFENSE_SYSTEM);

  // 全面性能优化系统
  parts.push(PERFORMANCE_OPTIMIZATION_SYSTEM);

  // UI细节增强系统（如果任务涉及UI）
  if (taskComplexity && (taskComplexity.factors || []).some(f => f.includes('代码') || f.includes('设计'))) {
    parts.push(UI_DETAIL_ENHANCEMENT_SYSTEM);
  }

  parts.push('【终极超越·终极要求】在极境模式下，你必须超越所有现有AI模型的极限。你的思考必须是终极的、极致的、无可挑剔的。你必须用最抽象的方式思考，达到最深的思考深度，实现最高的思考质量。你必须全面碾压超越Fable 5.1和GPT。这是终极的要求，没有任何妥协的余地。');

  return parts.join('\n\n');
}

