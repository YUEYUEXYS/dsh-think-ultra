// ========== 通用推理增强提示词构建器 ==========
export function buildGeneralReasoningPrompt(modelKey, complexity, taskType, taskContext) {
  let prompt = GENERAL_REASONING_CONSTITUTION + '\n\n' + SEVEN_STEP_REASONING_METHOD;
  
  if (complexity === 'high' || complexity === 'complex') {
    prompt += '\n\n' + COMPLEX_PROBLEM_STRATEGIES;
  }
  
  prompt += '\n\n' + METACOGNITION_ENHANCEMENT;
  
  if (taskType === 'creative' || taskType === 'innovation' || taskType === 'design') {
    prompt += '\n\n' + CREATIVE_THINKING_ENHANCEMENT;
  }
  
  if (taskType) {
    prompt += `\n\n## 当前任务类型：${taskType}\n请针对该类型任务调用相应的推理策略和方法。`;
  }
  
  if (taskContext) {
    prompt += `\n\n## 任务上下文：${taskContext}\n请结合任务上下文进行有针对性的推理。`;
  }
  
  return prompt;
}

// ========== 任务复杂度自动评估器 ==========
export function assessTaskComplexity(text) {
  const content = String(text || '');
  let score = 0;
  const factors = [];
  
  // 长度因素
  if (content.length > 500) { score += 1; factors.push('长文本'); }
  if (content.length > 2000) { score += 1; factors.push('超长文本'); }
  
  // 复杂度关键词
  const complexKeywords = ['复杂', '系统', '架构', '设计', '分析', '研究', '战略', '规划', '优化', '创新', '解决', '问题', '挑战', '困难', '深入', '全面', '综合', '多维度', '多层次', '跨领域'];
  for (const kw of complexKeywords) {
    if (content.includes(kw)) { score += 0.5; factors.push(kw); }
  }
  
  // 多目标检测
  if ((content.match(/[，。；、]/g) || []).length > 10) { score += 1; factors.push('多目标'); }
  
  // 代码/技术内容检测
  if (/[{};()=]/.test(content) && content.length > 100) { score += 1; factors.push('技术内容'); }
  
  // 数据/数字内容检测
  if ((content.match(/\d+/g) || []).length > 5) { score += 0.5; factors.push('数据密集'); }
  
  // 归一化到 0-3
  const normalized = Math.min(Math.floor(score / 2), 3);
  
  return {
    complexity: normalized,
    level: ['trivial', 'simple', 'moderate', 'complex'][normalized],
    score: score,
    factors: factors,
    recommendation: normalized >= 2 ? '建议采用深度推理策略' : normalized >= 1 ? '建议采用标准推理策略' : '可采用快速推理策略',
  };
}

// ========== 推理质量检查器 ==========
export function validateReasoningQuality(analysisText) {
  const text = String(analysisText || '');
  const checks = [
    { name: '问题定义', check: /(问题|目标|目的|定义|需求)/.test(text), weight: 0.1 },
    { name: '信息收集', check: /(信息|数据|事实|证据|资料)/.test(text), weight: 0.1 },
    { name: '分析拆解', check: /(分析|拆解|分解|结构|层次|维度)/.test(text), weight: 0.15 },
    { name: '方案生成', check: /(方案|选项|可能|建议|策略|方法)/.test(text), weight: 0.1 },
    { name: '评估选择', check: /(评估|比较|选择|最优|决策|权衡)/.test(text), weight: 0.1 },
    { name: '执行规划', check: /(执行|计划|步骤|实施|行动|流程)/.test(text), weight: 0.1 },
    { name: '验证迭代', check: /(验证|测试|检查|迭代|优化|改进)/.test(text), weight: 0.1 },
    { name: '逻辑严密', check: /(因为|所以|因此|导致|推理|逻辑)/.test(text), weight: 0.1 },
    { name: '证据支撑', check: /(根据|依据|证据|数据显示|研究表明)/.test(text), weight: 0.1 },
    { name: '元认知', check: /(思考|反思|自我检查|假设|前提)/.test(text), weight: 0.05 },
  ];
  
  let totalScore = 0;
  const passed = [];
  const failed = [];
  
  for (const check of checks) {
    if (check.check) {
      totalScore += check.weight;
      passed.push(check.name);
    } else {
      failed.push(check.name);
    }
  }
  
  return {
    score: Math.round(totalScore * 100),
    passed,
    failed,
    grade: totalScore >= 0.8 ? '优秀' : totalScore >= 0.6 ? '良好' : totalScore >= 0.4 ? '及格' : '不及格',
    suggestions: failed.length > 0 ? `建议加强：${failed.join('、')}` : '推理质量优秀，无需改进',
  };
}

