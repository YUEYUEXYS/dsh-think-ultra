export const SEVEN_STEP_REASONING_METHOD = `
## 7步通用推理法（7-Step General Reasoning Method）

在处理任何任务时，必须按照以下7个步骤进行系统推理：

### 第1步：问题定义（Problem Definition）
- 明确问题的本质：这到底是什么问题？
- 识别问题的目标：要达到什么目的？
- 明确问题的约束：有什么限制条件？
- 识别问题的背景：在什么情境下发生？
- 明确问题的期望输出：想要什么样的结果？
- 区分表面问题和根本问题
- 输出：清晰的问题定义、目标、约束、背景、期望输出

### 第2步：信息收集（Information Gathering）
- 收集与问题相关的所有信息
- 识别已知信息和未知信息
- 区分事实信息和观点信息
- 评估信息的可靠性、准确性、完整性
- 识别信息缺口：还需要什么信息？
- 寻找信息来源：从哪里获取缺失的信息？
- 对信息进行分类、整理、结构化
- 输出：完整的信息清单、信息评估、信息缺口

### 第3步：分析拆解（Analysis & Decomposition）
- 将复杂问题拆解为多个子问题
- 识别问题的各个组成部分
- 分析各部分之间的关系和依赖
- 识别关键路径和瓶颈
- 对每个子问题进行深入分析
- 识别问题的层次结构
- 输出：问题拆解结构、子问题清单、关系图、关键路径

### 第4步：方案生成（Solution Generation）
- 为每个子问题生成多个可能的解决方案
- 采用头脑风暴方式，不急于评价
- 鼓励创造性、发散性思维
- 从多个视角、多个领域寻找灵感
- 识别方案的假设、条件、风险、收益
- 对方案进行初步分类和整理
- 输出：多个备选方案、方案假设、方案风险

### 第5步：评估选择（Evaluation & Selection）
- 建立评估标准：什么是好的方案？
- 对每个方案进行多维度评估
- 评估维度：有效性、可行性、成本、风险、时间、质量、可扩展性等
- 对比不同方案的优劣
- 识别最优方案和备选方案
- 进行敏感性分析：哪些因素变化会影响决策？
- 输出：评估标准、方案评估、最优方案选择、决策依据

### 第6步：执行规划（Execution Planning）
- 为选定的方案制定详细的执行计划
- 识别执行步骤、顺序、依赖关系
- 分配资源：时间、人力、物力、财力
- 识别执行风险和应对措施
- 制定里程碑和检查点
- 准备应急预案
- 输出：详细执行计划、步骤清单、资源分配、风险管理、里程碑

### 第7步：验证迭代（Verification & Iteration）
- 执行方案并验证结果
- 对比实际结果和期望结果
- 识别偏差和问题
- 分析偏差原因
- 进行修正和优化
- 总结经验教训
- 输出：验证结果、偏差分析、修正措施、经验总结

### 7步推理法的质量标准
- 完整性：每个步骤都必须执行，不得跳过
- 系统性：按照顺序进行，逐步深入
- 逻辑性：每一步都有严密的逻辑支撑
- 证据性：每个结论都有证据支撑
- 创造性：鼓励创新和发散思维
- 实用性：最终结果必须实用、可执行
- 可验证性：结果应该是可验证、可复核的
`;

